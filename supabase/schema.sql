-- Heartbeat schema. Shared file: tell the team before changing it.
-- Run once in the Supabase SQL editor. Safe to re-run: it drops and recreates.

-- Old ladder tables from the first skeleton go first: they reference clients.
drop table if exists call_logs;
drop table if exists checks;
drop table if exists events;
drop table if exists alerts;
drop table if exists calls;
drop table if exists crisis_runs;
drop table if exists daily_entries;
drop table if exists clients;

-- Small integer ids so demo curl commands stay short. Seed sets them explicitly.
create table clients (
  id int generated by default as identity primary key,
  name text not null,
  preferred_name text not null,
  room text not null,
  phone text not null,
  aide_name text not null,
  nurse_name text not null,
  allergies text,
  personal_note text,
  -- { "bp_sys": { "min": 100, "max": 150 }, ... } set by the nurse
  vitals_ranges jsonb not null default '{}',
  created_at timestamptz not null default now()
);

create table daily_entries (
  id int generated by default as identity primary key,
  client_id int not null references clients (id) on delete cascade,
  date date not null,
  bp_sys int,
  bp_dia int,
  heart_rate int,
  temp_f double precision,
  spo2 int,
  vitals_watch_note text,
  med_schedule_now text,
  entered_by text,
  created_at timestamptz not null default now(),
  unique (client_id, date)
);

create table crisis_runs (
  id int generated by default as identity primary key,
  crisis_type text not null,
  started_at timestamptz not null default now(),
  ended_at timestamptz
);

create table calls (
  call_id text primary key,
  client_id int not null references clients (id) on delete cascade,
  call_type text not null check (call_type in ('daily', 'crisis')),
  crisis_type text,
  crisis_run_id int references crisis_runs (id) on delete set null,
  status text not null default 'registered'
    check (status in ('registered', 'ongoing', 'ended', 'analyzed')),
  started_at timestamptz,
  ended_at timestamptz,
  duration_sec int,
  disconnection_reason text,
  summary text,
  sentiment text,
  call_successful boolean,
  -- Retell post-call extraction fields. Null when the agent did not fill them.
  feels_ok text,
  danger_words_heard boolean,
  med_taken text,
  allergy_item_mentioned boolean,
  dose_question_asked boolean,
  needs_nurse boolean,
  needs_nurse_reason text,
  new_personal_fact text,
  answered_by text,
  pain_level int,
  pain_location text,
  sleep_quality text,
  ate_and_drank text,
  steady_on_feet text,
  mood text,
  new_swelling boolean,
  crisis_status text,
  transcript text,
  raw_json jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index calls_client_idx on calls (client_id, created_at desc);
create index calls_status_idx on calls (status);
create index calls_run_idx on calls (crisis_run_id);

create table alerts (
  id int generated by default as identity primary key,
  client_id int not null references clients (id) on delete cascade,
  call_id text references calls (call_id) on delete set null,
  type text not null,
  urgency text not null check (urgency in ('now', 'today')),
  message text not null,
  quote text,
  -- "<call_id>:<type>" so a repeated webhook never makes a second alert. Null means no dedup.
  dedup_key text unique,
  created_at timestamptz not null default now(),
  acknowledged_at timestamptz,
  acknowledged_by text
);

create index alerts_open_idx on alerts (client_id) where acknowledged_at is null;

-- Keep calls.updated_at fresh.
create or replace function touch_updated_at() returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

create trigger calls_touch before update on calls
  for each row execute function touch_updated_at();

-- Reads with the anon key are allowed for the frontend. All writes go through API routes.
alter table clients enable row level security;
alter table daily_entries enable row level security;
alter table crisis_runs enable row level security;
alter table calls enable row level security;
alter table alerts enable row level security;

create policy "anon read clients" on clients for select using (true);
-- The anon key never sees resident phone numbers. Every column but phone is readable.
revoke select on clients from anon;
grant select (id, name, preferred_name, room, aide_name, nurse_name, allergies, personal_note, vitals_ranges, created_at)
  on clients to anon;
create policy "anon read daily_entries" on daily_entries for select using (true);
create policy "anon read crisis_runs" on crisis_runs for select using (true);
create policy "anon read calls" on calls for select using (true);
create policy "anon read alerts" on alerts for select using (true);

-- Realtime as a fallback to the /api/events stream.
alter publication supabase_realtime add table calls;
alter publication supabase_realtime add table alerts;
alter publication supabase_realtime add table crisis_runs;
